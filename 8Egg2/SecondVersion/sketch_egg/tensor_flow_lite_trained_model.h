void setupLED() {
  pinMode(SI_LED_PIN, OUTPUT);
  digitalWrite(SI_LED_PIN, LOW);
  pinMode(NO_LED_PIN, OUTPUT);
  digitalWrite(NO_LED_PIN, LOW);
  pinMode(BASURA_LED_PIN, OUTPUT);
  digitalWrite(BASURA_LED_PIN, LOW);
}

void setLedsByPrediction(int leds_to_turn_on) {
   // Control de LEDs
  switch (leds_to_turn_on) {
	case 0:
  	digitalWrite(SI_LED_PIN, LOW);
  	digitalWrite(NO_LED_PIN, LOW);
  	digitalWrite(BASURA_LED_PIN, HIGH);
  	break;

	case 1:
  	digitalWrite(SI_LED_PIN, LOW);
  	digitalWrite(NO_LED_PIN, HIGH);
  	digitalWrite(BASURA_LED_PIN, LOW);
  	break;

	case 2:
  	digitalWrite(SI_LED_PIN, HIGH);
  	digitalWrite(NO_LED_PIN, LOW);
  	digitalWrite(BASURA_LED_PIN, LOW);
  	break;

	default:
  	// Por seguridad, apagar todo
  	digitalWrite(SI_LED_PIN, LOW);
  	digitalWrite(NO_LED_PIN, LOW);
  	digitalWrite(BASURA_LED_PIN, LOW);
  	break;
  }
  }

